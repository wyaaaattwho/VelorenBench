"""No-world declaration/registration helper; stdlib + public benchmark core only.

Can also be executed as a file by the evaluator's minimal interpreter:
    /absolute/core/bin/python -I /installed/dsh_external_v1/binding.py --help
"""
import argparse
import asyncio
import json
import os
from pathlib import Path
import subprocess
import sys

from scripts.rpg_benchmark import capabilities, external, lifecycle, runtime

IDENTIFIER = "deepseek-harness"
CAPABILITIES = {
    "native_protocol": "0.2", "integer_transport": "strict", "asynchronous_receipts": True,
    "backends": ["headless", "renderer"], "player_tools": "rpg-player-tools/1",
    "image_transport": "image-blocks-v1", "observation_modes": ["structured", "image", "hybrid"],
    "model_profiles": [{"model": "gpt-6-luna", "reasoning_efforts": ["none"]}],
    "action_profiles": ["raw-native-v2", "ordinary-renderer-native-v1",
                        "visual-motor-v1", "visual-ui-v1"],
    "action_profiles_by_observation_mode": {
        "structured": ["raw-native-v2", "ordinary-renderer-native-v1"],
        "hybrid": ["ordinary-renderer-native-v1"],
        "image": ["visual-motor-v1", "visual-ui-v1"]},
}
DEFAULT = {"model": "gpt-6-luna", "reasoning_effort": "none",
           "observation_mode": "structured", "action_profile": "ordinary-renderer-native-v1"}


def absolute(path, *, python=False):
    path = Path(path)
    if not path.is_absolute():
        raise ValueError("Supply absolute local paths")
    return runtime.local_path(Path.cwd(), str(path), python=python)


def package_inventory(root):
    """Only shipped implementation/data, not interpreter-generated bytecode."""
    return {str(p.relative_to(root)): lifecycle.sha(p) for p in sorted(root.rglob("*"))
            if p.is_file() and p.suffix in {".py", ".mjs", ".json", ".lock"}
            and "__pycache__" not in p.parts}


def runtime_inventory(root):
    """Hash installed npm bytes, including internal executable symlink targets.

    Do not capture account configuration, caches, logs or unrelated runtime files.
    The official npm .bin links are allowed only within this node_modules tree.
    """
    root = absolute(root)
    modules = root / "node_modules"
    if not modules.is_dir() or modules.is_symlink():
        raise ValueError("Installed node_modules directory required")
    paths = [root / "package.json", root / "package-lock.json", *sorted(modules.rglob("*"))]
    files = {}
    for path in paths:
        if path.is_symlink() and (not path.is_file()
                                 or not path.resolve().is_relative_to(modules)):
            raise ValueError("Runtime symlink must resolve to an internal regular file")
        if path.is_file():
            files[str(path.relative_to(root))] = lifecycle.sha(path)
    if not {"package.json", "package-lock.json", "node_modules/.bin/dsh"} <= files.keys():
        raise ValueError("Complete pinned npm installation required")
    return files


def write(path, value):
    with path.open("x", encoding="utf-8") as stream:
        stream.write(json.dumps(value, sort_keys=True, indent=2, allow_nan=False) + "\n")
    return lifecycle.sha(path)


def probe(python, selected_runtime, extra=()):
    python = absolute(python, python=True)
    if not python.is_file() or not os.access(python, os.X_OK):
        raise ValueError("Adapter interpreter is not executable")
    args = ["-B", "-m", "dsh_external_v1.preflight", *extra, "--runtime", str(selected_runtime)]
    result = subprocess.run([str(python), "-I", *args], env=external.clean_environment(),
                            stdout=subprocess.PIPE, stderr=subprocess.STDOUT, timeout=60)
    if result.returncode:
        raise ValueError("Adapter preflight failed: " + result.stdout.decode(errors="replace").strip())
    receipt = json.loads(result.stdout)
    if (receipt.get("schema") != "rpg-adapter-preflight/1"
            or receipt.get("player_package_files") != runtime.package_files()):
        raise ValueError("Adapter must install the exact evaluator player package; content differs")
    return args, receipt


def rebase(config, base):
    result = dict(config)
    for key in ("native", "renderer", "renderer_fixture_helper", "native_interactions",
                "sources", "external_adapters"):
        if key in result:
            result[key] = {name: str(runtime.local_path(base, path))
                           for name, path in result[key].items()}
    result["python"] = sys.executable
    return result


def startup_preflight(adapter, out):
    # Renderer construction needs explicit frame storage even for structured
    # observations. Detail storage is independent; neither opens a world/model.
    return asyncio.run(adapter.preflight(
        backend="renderer", frames=out / "preflight-frames",
        detail_storage=out / "preflight-details"))


def bind(*, config, config_sha256, python, selected_runtime, out, output_root,
         observation_mode="structured", action_profile="ordinary-renderer-native-v1",
         admit_model_calls=False):
    config, selected_runtime, out, output_root = map(
        absolute, (config, selected_runtime, out, output_root))
    python = absolute(python, python=True)
    # All input checks, including the actual private-env imports, precede output creation.
    base_selected = runtime.load_runtime(config, config_sha256, backend="renderer")
    base = runtime.read_json(config, config_sha256)
    content = runtime.read_json(runtime.local_path(config.parent, base["content"]["path"]),
                                base["content"]["sha256"])
    defaults = {**DEFAULT, "observation_mode": observation_mode, "action_profile": action_profile}
    negotiated, declared, _ = capabilities.negotiate(
        {"schema": capabilities.PROCESS_SCHEMA, "capabilities": CAPABILITIES,
         "default_configuration": defaults}, {})
    capabilities.admit_backend(negotiated, declared, "renderer")
    _, receipt = probe(python, selected_runtime)
    root = absolute(receipt["adapter_root"])
    files = package_inventory(root)
    if files != receipt["adapter_package_files"] or "adapter.py" not in files:
        raise ValueError("Installed adapter source identity changed")
    runtime_files = runtime_inventory(selected_runtime)
    # The user's output must not overlap any inputs, including external runtime/package.
    protected = [Path(p) for p in base_selected["protected_paths"]]
    for destination in (out, output_root):
        runtime.exclude_outputs(destination, [*protected, config, root, selected_runtime, python])
    if out == output_root or out.is_relative_to(output_root) or output_root.is_relative_to(out):
        raise ValueError("Keep binding and episode outputs separate")
    if out.exists():
        raise ValueError("Binding output already exists; use a new directory")
    out.mkdir(parents=True, exist_ok=False)
    native_freeze = out / "runtime-freeze.json"
    write(native_freeze, {"root": str(selected_runtime), "files": runtime_files})
    freeze = out / "adapter-freeze.json"
    write(freeze, {"root": str(root), "files": files,
                   "parents": [{"path": str(native_freeze), "sha256": lifecycle.sha(native_freeze)}]})
    preflight = ["-B", "-m", "dsh_external_v1.preflight",
                 "--runtime-freeze", str(native_freeze),
                 "--runtime-freeze-sha256", lifecycle.sha(native_freeze),
                 "--runtime", str(selected_runtime)]
    declaration = out / "deepseek-harness.json"
    declaration_sha = write(declaration, {
        "schema": capabilities.PROCESS_SCHEMA, "id": IDENTIFIER,
        "player_interface": external.PLAYER, "tool_track": "official-dsh-common-player",
        "implementation": str(root / "adapter.py"), "implementation_sha256": files["adapter.py"],
        "freeze": {"path": str(freeze), "sha256": lifecycle.sha(freeze)},
        "runtime": {"python": str(python), "preflight": preflight},
        "capabilities": CAPABILITIES, "default_configuration": defaults})
    local = rebase(base, config.parent)
    local["external_adapters"] = {**local["external_adapters"], IDENTIFIER: str(declaration)}
    content["external_adapters"] = {**content["external_adapters"], IDENTIFIER: declaration_sha}
    local["output_root"] = str(output_root)
    content_path, runtime_path = out / "content.json", out / "runtime.json"
    local["content"] = {"path": str(content_path), "sha256": write(content_path, content)}
    pins_sha = write(runtime_path, local)
    selected = runtime.load_runtime(runtime_path, pins_sha, backend="renderer")
    admission = None
    if admit_model_calls:
        admission = out / "admission.json"
        write(admission, {
            "schema": external.LIVE, "live": True, "provider": "existing-luna",
            "pins_sha256": pins_sha, "adapter_id": IDENTIFIER,
            "adapter_sha256": declaration_sha, "model": negotiated["model"],
            "reasoning_effort": negotiated["reasoning_effort"],
            "configuration": negotiated, "adapter_config": {"runtime": str(selected_runtime)},
            "model_calls_admitted": True})
    # Synthetic configuration is used only for dependency preflight: no connection is made.
    adapter = external.Adapter(
        selected, IDENTIFIER,
        {"runtime": str(selected_runtime), **({} if admission else
                                             {"mock_provider": "http://127.0.0.1:9"})},
        engineering=admission is None, admission=admission, pins_sha=pins_sha)
    checked = startup_preflight(adapter, out)
    result = {
        "status": "staged-inputs-validated-not-native-qualified",
        "runtime": str(runtime_path), "runtime_sha256": pins_sha,
        "declaration": str(declaration), "declaration_sha256": declaration_sha,
        "freeze_sha256": lifecycle.sha(freeze),
        "adapter_config": {"runtime": str(selected_runtime)}, "configuration": negotiated,
        "admission": str(admission) if admission else None, "preflight": checked,
        "native_worlds": 0, "model_calls": 0,
    }
    write(out / "binding-receipt.json", result)
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, required=True,
                        help="Existing standard bind-native runtime.json; never modified")
    parser.add_argument("--config-sha256", required=True)
    parser.add_argument("--python", type=Path, required=True, help="Installed adapter interpreter")
    parser.add_argument("--runtime", type=Path, required=True, help="Installed pinned official npm runtime")
    parser.add_argument("--out", type=Path, required=True, help="New local registration directory")
    parser.add_argument("--output-root", type=Path, required=True, help="Separate local episode root")
    parser.add_argument("--observation-mode", choices=("structured", "hybrid", "image"), default="structured")
    parser.add_argument("--action-profile", default="ordinary-renderer-native-v1")
    parser.add_argument("--admit-model-calls", action="store_true",
                        help="Declare caller-selected live provider/configuration; no service authorization implied")
    args = parser.parse_args()
    try:
        value = bind(config=args.config, config_sha256=args.config_sha256, python=args.python,
                     selected_runtime=args.runtime, out=args.out, output_root=args.output_root,
                     observation_mode=args.observation_mode, action_profile=args.action_profile,
                     admit_model_calls=args.admit_model_calls)
    except (ValueError, OSError, KeyError, subprocess.SubprocessError) as error:
        parser.exit(2, f"velorenbench-dsh-bind: {type(error).__name__}: {error}\n")
    print(json.dumps(value, indent=2, allow_nan=False))


if __name__ == "__main__":
    main()
