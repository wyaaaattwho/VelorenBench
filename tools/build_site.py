"""Generate the public compendium from unchanged task definitions and editorial notes."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
FAMILIES = [
    ("navigation_tasks", "✧", "Information Seeking & Dynamic Route Adaptation", "信息搜寻与动态路线适应"),
    ("crafting_recovery", "❧", "Crafting & Health Recovery", "制作与生命恢复"),
    ("crafting", "⚒", "Foundational & Multi-Station Crafting", "基础与多工作站制作"),
    ("combat", "⚔", "Combat Encounters", "战斗遭遇"),
    ("combat_support", "♜", "Tactical Combat Builds & Companion Support", "战斗构筑与同伴支援"),
    ("navigation", "⌖", "Spatial & Town Navigation", "空间与城镇导航"),
    ("mixed", "◇", "Mixed Multi-Objective Horizons", "混合多目标长程任务"),
    ("npc_contracts", "✉", "NPC Trade & Quest Contracts", "NPC交易与任务合同"),
]
SOURCES = {
    "navigation_tasks": "navigation_tasks.py", "crafting_recovery": "crafting_recovery.py",
    "crafting": "crafting.py", "combat": "combat.py", "combat_support": "combat_support.py",
    "navigation": "navigation.py", "mixed": "mixed.py", "npc_contracts": "npc_contracts.py",
}


def generate():
    scenes = json.loads((ROOT / "harness/scripts/rpg_benchmark/scenes.json").read_text())["scenes"]
    notes = json.loads((ROOT / "docs/task_notes.json").read_text())
    assert set(notes) == {s["id"] for s in scenes}
    catalog = (ROOT / "TASKS.md").read_text().split("<!-- BEGIN GENERATED SUCCESSOR -->")[1]
    requirements = {}
    for line in catalog.splitlines():
        cells = [p.strip() for p in line.strip("|").split("|")]
        if len(cells) == 5 and cells[0] in notes:
            requirements[cells[0]] = cells[4].split(", ")
    assert set(requirements) == set(notes)
    descriptions = {}
    for line in (ROOT / "TASKS.md").read_text().split("<!-- BEGIN GENERATED SUCCESSOR -->")[0].splitlines():
        cells = [p.strip() for p in line.strip("|").split("|")]
        if len(cells) == 4 and cells[0] in notes:
            descriptions[cells[0]] = cells[3]
    tasks = []
    md = []
    for family, icon, en, zh in FAMILIES:
        md.append(f"### {icon} {en}\n")
        for scene in scenes:
            if scene["kind"] != family:
                continue
            task_id = scene["id"]
            note = {key: [re.sub(r"\b([a-z]{2,})(?=\d)", r"\1 ", value[0]), value[1]]
                    for key, value in notes[task_id].items()}
            source = "harness/scripts/rpg_benchmark/" + SOURCES[family]
            task = {
                "id": task_id, "family": family, "icon": icon,
                "terrain": scene["terrains"], "capabilities": requirements[task_id],
                "modalities": ["structured", "hybrid", "image"],
                "imagePolicy": "task-engineering-only" if task_id == "T05" else "exact-key-admission",
                "image": f"assets/tasks/{task_id}.png", "source": source,
                "en": {"title": note["title"][0], "initial": note["initial"][0],
                       "challenge": note["challenge"][0], "oracle": note["oracle"][0]},
                "zh": {"title": note["title"][1], "initial": note["initial"][1],
                       "challenge": note["challenge"][1], "oracle": note["oracle"][1]},
                "publicGoal": scene.get("task", descriptions[task_id]),
                "goalKind": "authored" if "task" in scene else "fixture-generated-catalog-description",
            }
            tasks.append(task)
            md.extend([
                f'<details id="task-{task_id.lower()}">\n<summary><b>{task_id} · {note["title"][0]}</b></summary>\n',
                f'![Native Veloren environment for {task_id}](docs/assets/tasks/{task_id}.png)\n',
                f'**Family:** {en}<br>\n**Terrain:** {", ".join(scene["terrains"])}<br>\n'
                f'**Required capabilities:** `{", ".join(requirements[task_id])}`<br>\n'
                '**Modalities:** Structured · Hybrid · Image (`visual-ui-v1`)'
                + (' — **task-engineering only for Image**.' if task_id == "T05" else ' — exact native-key admission applies.') + "\n",
                f'**Scenario & initial state.** {note["initial"][0]}\n',
                f'**Agent challenge.** {note["challenge"][0]}\n',
                f'**Native oracle.** {note["oracle"][0]}\n',
                f'**{"Authored goal" if "task" in scene else "Catalog description (runtime goal is fixture-generated)"}:** {task["publicGoal"]}\n',
                f'[Native scorer / fixture source]({source}) · [中文详情](https://wyaaaattwho.github.io/VelorenBench/#task={task_id})\n',
                '</details>\n',
            ])
    validation = json.loads((ROOT / "docs/validation.json").read_text())
    result = {"families": [{"id": f, "icon": i, "en": en, "zh": zh} for f, i, en, zh in FAMILIES],
              "tasks": tasks, "validation": validation}
    js = "// Generated by tools/build_site.py; do not edit by hand.\nwindow.VELOREN_DATA = " + json.dumps(
        result, ensure_ascii=False, indent=2) + ";\n"
    readme = (ROOT / "README.md").read_text()
    start, end = "<!-- BEGIN TASK COMPENDIUM -->", "<!-- END TASK COMPENDIUM -->"
    assert readme.count(start) == readme.count(end) == 1
    new_readme = readme.split(start)[0] + start + "\n\n" + "\n".join(md) + "\n" + end + readme.split(end)[1]
    return {ROOT / "docs/tasks_data.js": js, ROOT / "README.md": new_readme}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = generate()
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"Generated site content differs: {path.relative_to(ROOT)}")
        else:
            path.write_text(content)
    print("Verified" if args.check else "Generated", "29 tasks / 8 families; original goals untouched")


if __name__ == "__main__":
    main()
